// The texts of the organization's profiles outside the site, ready to paste: docs/profiles/README.md (where the
// profiles are), youtube.md and linkedin.md, and every LinkedIn article of src/content/profiles/articles as Markdown and
// as HTML for the article editor (docs/profiles/linkedin-articles/). Everything comes from src/content/profiles and
// src/data/profiles.ts, which Node loads as TypeScript without a bundler. The texts are checked against the platforms'
// limits, and public/llms.txt must list every profile.
//
//   npm run profiles        exit 1 when a text is over a limit or a profile is missing from llms.txt
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const load = (file) => import(pathToFileURL(path.join(root, file)).href);
const P = await load('src/data/profiles.ts');
const { LANGS, LANG_LABEL } = await load('src/i18n/config.ts');
const { PROFILES, LIMITS } = P;

const out = path.join(root, 'docs', 'profiles');
const problems = [];
/** "123/500", and a problem when the text is over the limit */
function count(what, length, limit) {
  if (length > limit) problems.push(`${what}: ${length} characters, the limit is ${limit}`);
  return `${length}/${limit}`;
}
const box = (text) => ['```text', text, '```'];
const NAME = { en: 'English', pl: 'Polish', de: 'German' };
const GENERATED = 'Generated by `npm run profiles` from `src/content/profiles/` and `src/data/profiles.ts`: change the texts there, not here. A text in a box is ready to paste; beside it, its length and the platform’s limit.';

// README: where the profiles are
const yt = PROFILES.youtube;
const li = PROFILES.linkedin;
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(
  path.join(out, 'README.md'),
  [
    '# Simon Lab outside the site',
    '',
    GENERATED,
    '',
    '| Where | Address | Texts |',
    '|---|---|---|',
    `| YouTube | ${yt.url} | [youtube.md](youtube.md) |`,
    `| LinkedIn | ${li.url} | [linkedin.md](linkedin.md) |`,
    '',
    `- Google: ${PROFILES.search.google}`,
    `- Bing: ${PROFILES.search.bing}`,
    '',
    '`npm run social` draws the images into [images/](images/) from the site’s own brand files: the channel’s picture and banner, the LinkedIn logo and cover (the logos without a background, for light and dark pages), the samples of work in LinkedIn’s Services section, the films’ thumbnails and the covers of the LinkedIn articles.',
    '',
    '## Changing a profile',
    '',
    '1. Change the copy in `src/content/profiles/` (English first, then Polish and German with the same facts) or the facts in `src/data/profiles.ts`.',
    '2. Run `npm run profiles` (and `npm run social` for the images), then `npm run build` and `npm run check:copy`.',
    '3. Paste what changed into the platform, and commit the code together with `docs/profiles/`.',
    '',
  ].join('\n'),
);

// YouTube
const ys = yt.settings;
const yLines = [
  `# YouTube: ${ys.name}`,
  '',
  GENERATED,
  '',
  '## Channel',
  '',
  `- Address: ${yt.url} (channel ${yt.channelId})`,
  `- Name and handle: ${ys.name}, ${ys.handle}`,
  `- Country: ${ys.country}`,
  `- Links: ${ys.links.map((l) => `${l.title} ${l.url}`).join('; ')}`,
  `- Upload defaults: ${ys.uploadDefaults}`,
  `- Features: ${ys.features}`,
  '- Picture and banner: images/youtube-profile-800.png, images/youtube-banner-2560x1440.png',
  `- Playlist: "${yt.playlist}", both films`,
  `- Earlier uploads, private: ${yt.retired.join(', ')}`,
  '',
  `### Keywords (${count('YouTube keywords', P.tagLength(P.youtubeKeywords()), LIMITS.youtube.keywords)})`,
  '',
  ...box(P.youtubeKeywords().join(', ')),
];
for (const lang of LANGS) {
  const text = P.youtubeChannel(lang);
  const kind = lang === 'en' ? '' : ', a translation';
  yLines.push('', `### Description: ${NAME[lang]}${kind} (${count(`YouTube channel description (${lang})`, text.length, LIMITS.youtube.channel)})`, '', ...box(text));
}
for (const [film, f] of Object.entries(yt.films)) {
  const tags = P.youtubeTags(film);
  yLines.push(
    '',
    `## Film in ${f.language}: ${P.filmUrl(film)}`,
    '',
    `- Video language ${f.language}, ${f.duration}; captions: ${f.captions}`,
    `- Thumbnail: images/youtube-thumbnail-${film}-1280x720.jpg once the channel has the intermediate features`,
    '',
    `### Tags (${count(`YouTube tags (${film} film)`, P.tagLength(tags), LIMITS.youtube.tags)})`,
    '',
    ...box(tags.join(', ')),
  );
  for (const lang of LANGS) {
    const meta = P.youtubeFilm(film, lang);
    if (!meta) continue;
    const kind = lang === film ? '' : ', a translation';
    yLines.push(
      '',
      `### Title: ${NAME[lang]}${kind} (${count(`YouTube title (${film} film, ${lang})`, meta.title.length, LIMITS.youtube.title)})`,
      '',
      ...box(meta.title),
      '',
      `### Description: ${NAME[lang]}${kind} (${count(`YouTube description (${film} film, ${lang})`, meta.description.length, LIMITS.youtube.description)})`,
      '',
      ...box(meta.description),
    );
  }
}
fs.writeFileSync(path.join(out, 'youtube.md'), yLines.join('\n') + '\n');

// LinkedIn
const ls = li.settings;
const services = P.linkedinServices();
const media = P.linkedinServicesMedia();
const specialties = P.linkedinSpecialties();
const lLines = [
  `# LinkedIn: ${ls.name}`,
  '',
  GENERATED,
  '',
  '## Page',
  '',
  `- Address: ${li.url}`,
  `- Website: ${ls.website}`,
  `- Industry: ${ls.industry}`,
  `- Size: ${ls.size}; type: ${ls.type}; founded: ${ls.founded}`,
  `- Location: ${ls.location}`,
  `- Button: ${ls.button}`,
  `- Languages: ${ls.languages}`,
  '- Logo and cover: images/linkedin-logo-400.png, images/linkedin-cover-1128x191.png',
  '',
  '## Tagline',
];
for (const lang of LANGS) {
  const text = P.linkedinTagline(lang);
  lLines.push('', `### ${NAME[lang]} (${count(`LinkedIn tagline (${lang})`, text.length, LIMITS.linkedin.tagline)})`, '', ...box(text));
}
lLines.push('', '## About');
for (const lang of LANGS) {
  const text = P.linkedinAbout(lang);
  lLines.push('', `### ${NAME[lang]} (${count(`LinkedIn About (${lang})`, text.length, LIMITS.linkedin.about)})`, '', ...box(text));
}
lLines.push(
  '',
  `## Specialties (${count('LinkedIn specialties', specialties.length, LIMITS.linkedin.specialties)})`,
  '',
  ...box(specialties.join('\n')),
  '',
  '## Services',
  '',
  `- Page: ${ls.services.page}`,
  `- Services from LinkedIn’s list (${count('LinkedIn services', services.items.length, LIMITS.linkedin.services)}): ${services.items.join(', ')}`,
  `- Location: ${ls.services.location}; pricing: ${ls.services.pricing}; messages: ${ls.services.messages}`,
  '',
  `### Description (${count('LinkedIn services description', services.description.length, LIMITS.linkedin.servicesDescription)})`,
  '',
  ...box(services.description),
  '',
  `### Samples of work (${count('LinkedIn services media', media.pictures.length + 1, LIMITS.linkedin.servicesMedia)}), the pictures from images/`,
);
for (const m of media.pictures) {
  count(`LinkedIn services media title (${m.file})`, m.title.length, LIMITS.linkedin.servicesMediaTitle);
  count(`LinkedIn services media description (${m.file})`, m.description.length, LIMITS.linkedin.servicesDescription);
  lLines.push('', `- images/${m.file}: ${m.title}`, '', ...box(m.description));
}
count('LinkedIn services media title (the film)', media.film.title.length, LIMITS.linkedin.servicesMediaTitle);
lLines.push('', `- Link: ${media.film.url}`, '', ...box(media.film.title));

// LinkedIn articles: src/content/profiles/articles/<id>.<lang>.ts; drafts stay out of the public repository
const articlesDir = path.join(root, 'src', 'content', 'profiles', 'articles');
const articles = [];
if (fs.existsSync(articlesDir)) {
  for (const file of fs.readdirSync(articlesDir).filter((f) => f.endsWith('.ts')).sort()) {
    const { article } = await load(path.join('src', 'content', 'profiles', 'articles', file));
    if (article) articles.push(article);
  }
}
const escape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const linked = (s) => escape(s).replace(/https:\/\/[^\s<]+[^\s<.,;:)]/g, (url) => `<a href="${url}">${url}</a>`);
const published = [];
for (const a of articles) {
  const f = (s) => P.fill(s, { lang: a.lang, source: a.source, film: P.filmFor(a.lang) });
  const name = `${a.id}.${a.lang}`;
  const title = f(a.title);
  const words = a.blocks
    .flatMap((b) => Object.values(b).flat())
    .map(f)
    .join(' ')
    .split(/\s+/)
    .filter(Boolean).length;
  if (words > LIMITS.article.words) problems.push(`article ${name}: ${words} words, at most ${LIMITS.article.words}`);
  const [lo, hi] = LIMITS.article.seoDescription;
  const seo = a.seo.description.length;
  if (seo < lo || seo > hi) problems.push(`article ${name}: SEO description ${seo} characters, ${lo} to ${hi}`);
  if (a.hashtags.length > LIMITS.article.hashtags) problems.push(`article ${name}: ${a.hashtags.length} hashtags, at most ${LIMITS.article.hashtags}`);
  const cover = `images/linkedin-article-${a.id}-${a.lang}-1920x1080.jpg`;
  // each block as Markdown and as the HTML the article editor takes
  const blocks = a.blocks.map((b) => {
    if ('h2' in b) return [`## ${f(b.h2)}`, `<h2>${escape(f(b.h2))}</h2>`];
    if ('p' in b) return [f(b.p), `<p>${linked(f(b.p))}</p>`];
    if ('ul' in b) return [b.ul.map((x) => `- ${f(x)}`).join('\n'), `<ul>${b.ul.map((x) => `<li>${linked(f(x))}</li>`).join('')}</ul>`];
    if ('ol' in b) return [b.ol.map((x, i) => `${i + 1}. ${f(x)}`).join('\n'), `<ol>${b.ol.map((x) => `<li>${linked(f(x))}</li>`).join('')}</ol>`];
    if ('quote' in b) return [`> ${f(b.quote)}`, `<blockquote>${linked(f(b.quote))}</blockquote>`];
    return [f(b.embed), `<p>${linked(f(b.embed))}</p>`];
  });
  const tags = a.hashtags.map((tag) => `#${tag}`).join(' ');
  if (tags) blocks.push([tags, `<p>${escape(tags)}</p>`]);
  const md = blocks.flatMap(([text]) => [text, '']);
  const html = blocks.map(([, tag]) => tag);
  const facts = [
    `| Status | ${a.status} |`,
    `| Title (${count(`article ${name} title`, title.length, LIMITS.article.title)}) | ${title} |`,
    `| SEO title (${count(`article ${name} SEO title`, a.seo.title.length, LIMITS.article.seoTitle)}) | ${a.seo.title} |`,
    `| SEO description (${seo}, ${lo} to ${hi}) | ${a.seo.description} |`,
    `| Cover | ${cover} |`,
    `| Written from | ${P.pageUrl(a.source, a.lang)} |`,
    `| Words | ${words} |`,
  ];
  fs.mkdirSync(path.join(out, 'linkedin-articles'), { recursive: true });
  fs.writeFileSync(
    path.join(out, 'linkedin-articles', `${name}.md`),
    [`# LinkedIn article: ${title}`, '', GENERATED, '', '| | |', '|---|---|', ...facts, '', '---', '', `# ${title}`, '', ...md].join('\n'),
  );
  // for the article editor: the title has its own field, the body pastes as rich text
  fs.writeFileSync(
    path.join(out, 'linkedin-articles', `${name}.html`),
    `<!doctype html>\n<html lang="${a.lang}">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n<title>${escape(title)}</title>\n` +
      '<style>body{max-width:44rem;margin:2rem auto;padding:0 1rem;font:17px/1.6 system-ui,sans-serif;color:#1d1d1f}h1{font-size:2rem;line-height:1.2}h2{margin-top:2rem}img{max-width:100%}blockquote{margin:1rem 0;padding-left:1rem;border-left:3px solid #ccc;color:#444}</style>\n' +
      `</head>\n<body>\n<p><img src="../${cover}" alt=""></p>\n<h1>${escape(title)}</h1>\n<article>\n${html.join('\n')}\n</article>\n</body>\n</html>\n`,
  );
  if (a.status !== 'draft') published.push(`- ${a.status}: [${title}](linkedin-articles/${name}.md)`);
  console.log(`article ${name}: ${a.status}, ${words} words`);
}
// drafts stay out of the committed linkedin.md: only approved and published articles are listed
if (published.length) lLines.push('', '## Articles', '', ...published);
fs.writeFileSync(path.join(out, 'linkedin.md'), lLines.join('\n') + '\n');

// llms.txt lists every profile
const llms = fs.readFileSync(path.join(root, 'public', 'llms.txt'), 'utf8');
for (const [what, needle] of [['YouTube channel', yt.url], ['LinkedIn page', li.url], ...Object.entries(yt.films).map(([film, f]) => [`${film} film`, f.id])]) {
  if (!llms.includes(needle)) problems.push(`public/llms.txt does not list the ${what} (${needle})`);
}

for (const p of problems) console.log(`PROBLEM ${p}`);
console.log(`profiles: docs/profiles written (${LANGS.map((l) => LANG_LABEL[l]).join(', ')}), ${articles.length} article(s), ${problems.length} problem(s)`);
process.exit(problems.length ? 1 : 0);
